architecture sim of tb_i2c_master is
  -- ??????? ?? ?????????? ???????
  signal clk    : std_logic := '0';
  signal rst_n  : std_logic := '0';

  -- ????????? ?? DUT
  signal start   : std_logic := '0';
  signal addr    : std_logic_vector(6 downto 0) := (others => '0');
  signal rw      : std_logic := '0';
  signal data_in : std_logic_vector(7 downto 0) := (others => '0');
  signal data_out: std_logic_vector(7 downto 0);
  signal busy    : std_logic;

  -- ??????? ????? I2C (? ????????? ???? ?????? ???????????? ???????)
  signal sda_tb : std_logic := 'Z'; -- ??????, ???? ???'????????? ?? ????? inout DUT
  signal scl    : std_logic;

  -- ????????? ?????????
  constant CLK_PERIOD_NS : time := 20 ns; -- 50 MHz ???????

  -- ??????? ??? ???????? slave-?????????
  signal slave_active : std_logic := '0';
  signal slave_byte   : std_logic_vector(7 downto 0) := x"A5"; -- ????, ???? ??????? slave ??? ??? ???????
  signal slave_bit_idx: integer range 0 to 7 := 7;
  signal tb_done      : std_logic := '0';

begin
  ------------------------------------------------------------------
  -- ????????? DUT
  ------------------------------------------------------------------
  UUT: entity work.i2c_master
    generic map (PRESCALER => 50) -- ???????? ??? ??????? ?????????
    port map (
      clk => clk,
      rst_n => rst_n,
      start => start,
      addr => addr,
      rw => rw,
      data_in => data_in,
      data_out => data_out,
      busy => busy,
      sda => sda_tb,
      scl => scl
    );

  ------------------------------------------------------------------
  -- ???????? ?????????
  ------------------------------------------------------------------
  clk_gen: process
  begin
    while now < 200 ms loop
      clk <= '0';
      wait for CLK_PERIOD_NS/2;
      clk <= '1';
      wait for CLK_PERIOD_NS/2;
    end loop;
    wait;
  end process;

  ------------------------------------------------------------------
  -- ???????? ?? ??????
  ------------------------------------------------------------------
  stim_proc: process
  begin
    -- ????????? ????????
    rst_n <= '0';
    wait for 200 ns;
    rst_n <= '1';
    wait for 200 ns;

    -- ???? 1: ????? ?????? ????? (write)
    addr <= "0101010"; -- ??????? 7-?????? ??????
    rw <= '0'; -- ?????
    data_in <= x"5A";
    wait for CLK_PERIOD_NS; -- ????????? ? ??????
    -- ?????? ??????? ? ???????????? ???????
    start <= '1';
    wait for CLK_PERIOD_NS;
    start <= '0';

    -- ?????? ?? ?????????? ??????????
    wait until busy = '1';
    wait until busy = '0';
    report "Write transaction finished, continuing to read test";
    wait for 1 us;

    -- ???? 2: ??????? ?????? ????? (read)
    addr <= "0101010";
    rw <= '1'; -- ???????
    data_in <= (others => '0');

    -- ??????????? slave-????????: ?????????? ????? ????????? ?????
    slave_byte <= x"A5";
    -- slave_bit_idx <= 7; -- ???????? ?????? (Fix 2)
    wait for 200 ns;
    slave_active <= '1';

    wait for CLK_PERIOD_NS;
    start <= '1';
    wait for CLK_PERIOD_NS;
    start <= '0';

    -- ?????????? ?????????? ????????
    wait until busy = '1';
    wait until busy = '0';
    wait for 500 ns; -- ???????? ????? ??? ????????????

    -- ??????? (Fix 1: to_hstring)
    report "Read transaction finished, check data_out in waveform";
    tb_done <= '1';

    wait;
  end process;

  ------------------------------------------------------------------
  -- ??????? slave-???????? ??? ????????? Rx
  ------------------------------------------------------------------
  slave_proc: process
  begin
    wait until slave_active = '1';
    
    -- ?????? ???? (Fix 2: multiple drivers)
    slave_bit_idx <= 7; -- ????????????? ??????????
    
    -- ?????? ??????? ?????? SCL
    wait until scl = '0';
    wait for 1 ns;
    
    -- ?????????????? ???? ??? ??????? ??????? SCL
    while slave_active = '1' loop
      wait until scl = '0';
      -- ?????????? ??? ??? ??????????? ?????????? ??? ?????????? ??????? SCL
      sda_tb <= slave_byte(slave_bit_idx);
      wait until scl = '1'; -- master ?????? ?? ???????
      -- ????? ??????? ?????????? ??? ??????????? ????????? ??? ?? ???????
      if slave_bit_idx = 0 then
        -- ????????? ???????? 8 ?????
        slave_active <= '0';
        sda_tb <= 'Z';
        exit;
      else
        slave_bit_idx <= slave_bit_idx - 1;
        -- ?? ??????? ?????????? ????????? ???
        wait until scl = '0';
      end if;
    end loop;
    wait;
  end process;

  ------------------------------------------------------------------
  -- ?????????? ?????????
  ------------------------------------------------------------------
  finish_proc: process
  begin
    wait until tb_done = '1';
    wait for 1 us;
    report "Testbench finished";
    wait;
  end process;

end architecture;

